// Guards the root CHANGELOG.md against going stale behind the published version.
//
// Changesets generates packages/*/CHANGELOG.md and nothing generates this
// repository's root CHANGELOG.md, so it only stays current while someone
// remembers to write it. Twice now it has not been: 0.5.3-0.5.5 went unwritten
// (including a fix for cross-user response disclosure), and then 0.6.0 went
// unwritten, which is the largest security release the project has shipped.
// Both gaps were found by a reader going looking, which is exactly the reader
// the file exists for.
//
// The check is deliberately narrow: the newest release heading in the root
// changelog must name the version the packages are actually at. It says nothing
// about the entry's contents, because a shape check cannot tell a real writeup
// from a placeholder, and pretending otherwise would make this feel covered
// when it is not.
//
// A changesets "Version Packages" PR bumps package.json and the per-package
// changelogs in one commit, so this fails on that PR. That is the intended
// moment to write the entry: the release notes are the thing being reviewed,
// and the version bump is the only reliable trigger for remembering them.

import { readFileSync } from "node:fs";

const CHANGELOG = "CHANGELOG.md";
const VERSION_SOURCE = "packages/core/package.json";

const version = JSON.parse(readFileSync(VERSION_SOURCE, "utf8")).version;
const text = readFileSync(CHANGELOG, "utf8");

// Release headings look like `## [0.6.1] - 2026-07-27`. An "Unreleased" heading
// is allowed to sit above them and is not a release.
const headings = [...text.matchAll(/^## \[(\d+\.\d+\.\d+)\]/gm)].map((m) => m[1]);

if (headings.length === 0) {
  console.error(`${CHANGELOG} contains no "## [x.y.z]" release heading.`);
  process.exit(1);
}

const newest = headings[0];

if (newest !== version) {
  console.error(
    `Root changelog is behind the packages.\n` +
      `    ${VERSION_SOURCE} is at ${version}\n` +
      `    ${CHANGELOG}'s newest entry is ${newest}\n\n` +
      `Write the ${version} entry in ${CHANGELOG}. The per-package changelogs under\n` +
      `packages/*/CHANGELOG.md are generated by changesets and are the source to\n` +
      `write it from; this root file aggregates them and nothing generates it.`,
  );
  process.exit(1);
}

console.log(`Root changelog is current (newest entry ${newest} matches ${VERSION_SOURCE}).`);
